#!/usr/bin/env python3
"""Build paper/main.bib from refs-candidates.bib: only the keys cited in paper/sections, internal `note` fields
dropped (they hold our verification notes, not bibliographic data), Unicode dashes normalised.

    python paper/tools/make_bib.py
"""
import re, sys
from pathlib import Path

P = Path(__file__).resolve().parents[1]


def entries(text):
    i = 0
    while (m := re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,").search(text, i)):
        depth, j = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0); j += 1
        yield m.group(2), m.group(1), text[m.end():j - 1]
        i = j


def fields(body):
    i, out = 0, []
    while (m := re.compile(r"\s*,?\s*(\w+)\s*=\s*").match(body, i)) and m.end() < len(body):
        j = m.end()
        if body[j] in "{\"":
            close, depth, k = ("}" if body[j] == "{" else "\""), 0, j
            while True:
                c = body[k]
                if body[j] == "{":
                    depth += {"{": 1, "}": -1}.get(c, 0)
                    if depth == 0:
                        break
                elif c == "\"" and k > j:
                    break
                k += 1
            out.append((m.group(1), body[j:k + 1])); i = k + 1
        else:
            k = re.compile(r"[^,}]*").match(body, j).end(); out.append((m.group(1), body[j:k].strip())); i = k
    return out


def main():
    cited = set()
    for f in (P / "sections").glob("*.tex"):
        for m in re.finditer(r"\\cite\w*\{([^}]*)\}", f.read_text()):
            cited |= {k.strip() for k in m.group(1).split(",")}
    src = {k: (t, b) for k, t, b in entries((P / "refs-candidates.bib").read_text())}
    missing = sorted(cited - set(src))
    out = ["% GENERATED by paper/tools/make_bib.py from refs-candidates.bib (cited keys only) -- do not edit by hand.\n"]
    for k in sorted(cited & set(src)):
        t, b = src[k]
        fl = [(n, v.replace("\u2013", "--").replace("\u2014", "---")) for n, v in fields(b) if n.lower() != "note"]
        out.append(f"@{t}{{{k},\n" + ",\n".join(f"  {n} = {v}" for n, v in fl) + "\n}\n")
    (P / "main.bib").write_text("\n".join(out))
    print(f"{len(cited & set(src))} entries written; missing: {missing}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
